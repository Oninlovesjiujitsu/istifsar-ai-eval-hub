from pydantic import BaseModel, Field
from typing import List, Optional

class TracePayload(BaseModel):
    query: str = Field(..., description="The original query from the user")
    retrieved_context: List[str] = Field(..., description="List of historical context snippets retrieved by GraphRAG")
    generated_answer: str = Field(..., description="The final answer generated by the LLM")
    historian_notes: Optional[str] = Field(None, description="Optional notes or reasoning provided by the historian when flagging")
    timestamp: str = Field(..., description="ISO 8601 timestamp of when the flag occurred")
    record_id: str = Field(..., description="The Supabase UUID of the original generation record to update")
